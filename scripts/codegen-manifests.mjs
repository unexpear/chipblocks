#!/usr/bin/env node
/**
 * codegen-manifests.mjs — Sprint 2 codegen for the v2 ground-up
 * manifests. Reads each manifest YAML at repo root, validates against
 * its sibling JSON Schema, and emits a TypeScript registry module
 * into frontend/src/manifests/_generated/.
 *
 * Manifests handled (per ADR-006 + ADR-007):
 *   signals.yaml        -> _generated/signals.ts
 *   materials.yaml      -> _generated/materials.ts
 *   shapes.yaml         -> _generated/shapes.ts
 *   interfaces.yaml     -> _generated/interfaces.ts
 *   behaviors.yaml      -> _generated/behaviors.ts
 *   parameters.yaml     -> _generated/parameters.ts
 *
 * (provenance.schema.json is a $ref'd schema fragment with no
 * corresponding YAML; it's loaded into ajv for cross-schema
 * resolution but doesn't get its own generated module.)
 *
 * Modes:
 *   --check (default) — compute generated content + byte-diff
 *                       against the existing on-disk file; exit 1
 *                       with a unified diff if any target diverges.
 *   --write           — overwrite each target with the freshly
 *                       generated content.
 *
 * Invocation:
 *   node ../scripts/codegen-manifests.mjs            # --check
 *   node ../scripts/codegen-manifests.mjs --write    # regenerate
 *
 * Deps (frontend devDependencies):
 *   js-yaml ^4 ajv ^8
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(__dirname, '..')

// js-yaml + ajv live in frontend/node_modules (this script runs at
// repo root but depends on the frontend's devDependencies). Use
// createRequire pointed at frontend/package.json to resolve them.
const require = createRequire(resolve(REPO_ROOT, 'frontend/package.json'))
const yaml = require('js-yaml')
const Ajv = require('ajv')
const OUT_DIR = resolve(REPO_ROOT, 'frontend/src/manifests/_generated')

const MANIFESTS = [
  { name: 'signals', shape: 'array' },
  { name: 'materials', shape: 'array' },
  { name: 'shapes', shape: 'array' },
  { name: 'interfaces', shape: 'array' },
  { name: 'behaviors', shape: 'array' },
  { name: 'parameters', shape: 'object' },
]

const SCHEMAS_TO_LOAD = ['provenance', ...MANIFESTS.map((m) => m.name)]

function makeAjv() {
  const ajv = new Ajv({ allErrors: true, strict: false })
  for (const name of SCHEMAS_TO_LOAD) {
    const path = resolve(REPO_ROOT, `${name}.schema.json`)
    if (existsSync(path)) {
      ajv.addSchema(JSON.parse(readFileSync(path, 'utf-8')), `${name}.schema.json`)
    }
  }
  return ajv
}

function loadManifest(name) {
  const path = resolve(REPO_ROOT, `${name}.yaml`)
  return yaml.load(readFileSync(path, 'utf-8'))
}

function validate(ajv, name, manifest) {
  const schema = JSON.parse(
    readFileSync(resolve(REPO_ROOT, `${name}.schema.json`), 'utf-8'),
  )
  const validator = ajv.compile(schema)
  const ok = validator(manifest)
  if (!ok) {
    return { ok: false, errors: validator.errors }
  }
  return { ok: true, errors: null }
}

function generateModule(name, manifest) {
  const header = `// AUTO-GENERATED by scripts/codegen-manifests.mjs.
// Do not edit by hand. Run \`npm run codegen:write\` after editing
// ${name}.yaml at repo root.
//
// Source: ${name}.yaml + ${name}.schema.json
// See ADR-006 + ADR-007 for the data model.

`
  if (name === 'parameters') {
    // Object shape: { variables: { ... } }
    return (
      header +
      `export const ${name} = ${JSON.stringify(manifest, null, 2)} as const\n\n` +
      `export type ParametersManifest = typeof ${name}\n`
    )
  }
  // Array shape
  return (
    header +
    `export const ${name} = ${JSON.stringify(manifest, null, 2)} as const\n\n` +
    `export type ${capitalize(name)}Manifest = typeof ${name}\n`
  )
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

function processManifest(ajv, manifest) {
  const { name } = manifest
  const data = loadManifest(name)
  const { ok, errors } = validate(ajv, name, data)
  if (!ok) {
    console.error(`[codegen] ${name}.yaml fails schema validation:`)
    console.error(JSON.stringify(errors, null, 2))
    return null
  }
  return generateModule(name, data)
}

function targetPath(name) {
  return resolve(OUT_DIR, `${name}.ts`)
}

function main() {
  const mode = process.argv.includes('--write') ? 'write' : 'check'
  const ajv = makeAjv()

  if (!existsSync(OUT_DIR)) {
    if (mode === 'write') {
      mkdirSync(OUT_DIR, { recursive: true })
    } else {
      console.error(`[codegen] output directory ${OUT_DIR} does not exist`)
      console.error('  Run with --write to create it.')
      process.exit(1)
    }
  }

  let allOk = true
  for (const m of MANIFESTS) {
    const content = processManifest(ajv, m)
    if (content === null) {
      allOk = false
      continue
    }
    const path = targetPath(m.name)
    if (mode === 'write') {
      writeFileSync(path, content, 'utf-8')
      console.log(`[codegen] wrote ${path}`)
    } else {
      const existing = existsSync(path) ? readFileSync(path, 'utf-8') : ''
      if (existing !== content) {
        allOk = false
        console.error(`[codegen] DRIFT: ${path}`)
        console.error(
          `  Run \`npm run codegen:write\` to regenerate.`,
        )
        // Show a brief diff hint
        const existingLines = existing.split('\n').length
        const newLines = content.split('\n').length
        console.error(`  on disk: ${existingLines} lines; expected: ${newLines} lines`)
      }
    }
  }

  if (!allOk) {
    if (mode === 'write') {
      console.error('[codegen] errors during write — see above')
    }
    process.exit(1)
  }

  if (mode === 'check') {
    console.log('[codegen] all manifests in sync with generated TS modules')
  }
}

main()
